"""Generate immutable page build metadata from release.json; --check validates a release."""
import argparse
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
data = json.loads((root / 'release.json').read_text())
assert re.fullmatch(r'\d{4}\.\d{2}\.\d{2}\.\d+', data['version'])
assert data['date'] == data['version'][:10].replace('.', '-')
assert data['title'] and data['notes']
script = '// Generated by scripts/prepare_release.py; edit release.json.\nwindow.VOCAB_RELEASE = Object.freeze(' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ');\n'
files = {'release.js': script}
for name in ['vocabulary_app.html', 'index.html']:
    original = (root / name).read_text()
    if name == 'vocabulary_app.html':
        updated = re.sub(r'release\.js\?v=[^"\s]+', 'release.js?v=' + data['version'], original)
        assert updated.count('release.js?v=' + data['version']) == 1
    else:
        updated = re.sub(r'vocabulary_app\.html\?v=[^\'"\s<]+', 'vocabulary_app.html?v=' + data['version'], original)
    files[name] = updated
for name, content in files.items():
    if args.check:
        assert (root / name).read_text() == content, f'{name}: run python3 scripts/prepare_release.py'
    else:
        (root / name).write_text(content)
print('PASS: release metadata ' + data['version'])
